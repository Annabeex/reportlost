-- 1) lost_items : pays du signalement --------------------------------------
-- Ajout avec valeur par défaut constante : instantané sur Postgres 11+,
-- aucune réécriture de la table.
ALTER TABLE lost_items
  ADD COLUMN IF NOT EXISTS country text NOT NULL DEFAULT 'US';

-- Signalements déjà rattachés à une province canadienne (aucun code province
-- ne collisionne avec un code d'État US ; normalement zéro ligne).
UPDATE lost_items
SET country = 'CA'
WHERE country = 'US'
  AND upper(btrim(state_id)) IN ('AB','BC','MB','NB','NL','NS','NT','NU','ON','PE','QC','SK','YT');

-- 2) ca_cities : nom français et région --------------------------------------
ALTER TABLE ca_cities ADD COLUMN IF NOT EXISTS city_fr text;  -- "Grand Sudbury", "Québec" ; NULL = même nom
ALTER TABLE ca_cities ADD COLUMN IF NOT EXISTS region  text;  -- région économique ou administrative

-- 3) ca_city_guides : guides canadiens, un par ville ET par langue -----------
CREATE TABLE IF NOT EXISTS ca_city_guides (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  province_id  text        NOT NULL,                  -- "ON", "QC"
  city_ascii   text        NOT NULL,                  -- même valeur que ca_cities.city_ascii
  lang         text        NOT NULL,                  -- 'en' | 'fr'
  guide        jsonb       NOT NULL,
  status       text        NOT NULL DEFAULT 'draft',  -- 'draft' | 'published'
  verified     boolean     NOT NULL DEFAULT false,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (province_id, city_ascii, lang),
  -- Garde-fous contre le bug de l'espace parasite (« milford city »)
  CONSTRAINT ca_guides_lang_ok     CHECK (lang IN ('en','fr')),
  CONSTRAINT ca_guides_status_ok   CHECK (status IN ('draft','published')),
  CONSTRAINT ca_guides_province_ok CHECK (province_id = upper(btrim(province_id))),
  CONSTRAINT ca_guides_city_ok     CHECK (city_ascii = lower(btrim(city_ascii)) AND city_ascii <> '')
);

CREATE INDEX IF NOT EXISTS idx_ca_city_guides_published
  ON ca_city_guides (province_id, city_ascii, lang) WHERE status = 'published';

ALTER TABLE ca_city_guides ENABLE ROW LEVEL SECURITY;

